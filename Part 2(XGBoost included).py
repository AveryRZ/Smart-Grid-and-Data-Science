    # 用 np.linalg.solve 比直接求逆更稳定
    x_hat = np.linalg.solve(HTWH, HTWz)  # 13 x 1

    return x_hat.flatten()  # 返回为 1D 向量 (13,)# 假设已经有 train_X, train_y
