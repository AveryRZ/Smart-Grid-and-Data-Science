import numpy as np
from scipy.stats import chi2

# ----------------------------------------
# 1. 已有数据：
#    X      : (N, 34)  所有测量样本
#    H      : (34, 13) 测量矩阵（已去掉参考母线列）
#    W = R^{-1}: (34, 34) 权重矩阵
#    R_all  : (N, 34)  对应上面的循环算好的所有残差向量
# ----------------------------------------

# 如果你还没显式保存 R（协方差矩阵），可以由 W 反推：
# (可选，若你之前已经有 R，可直接使用之前的 R)
R = np.linalg.inv(W)  # (34, 34)

# 2. 为每个样本计算 BDD 统计量 J_i = r_i^T R^{-1} r_i = r_i^T W r_i
N = X.shape[0]
J_all = np.zeros(N)

for i in range(N):
    r_i = R_all[i, :].reshape(-1, 1)   # (34, 1)
    # 统计量 J_i = r_i^T W r_i   (也等价于 r_i^T R^{-1} r_i)
    J_all[i] = float(r_i.T @ W @ r_i)

print("J_all shape:", J_all.shape)     # (N,)

# 3. 计算卡方分布自由度：k = m - n
m = X.shape[1]      # 测量个数 m = 34
n = H.shape[1]      # 状态个数 n = 13 (bus 2~14 angles)
df = m - n          # degree of freedom = 34 - 13 = 21
print("Degree of freedom (df):", df)

# 4. 设定目标假正率 alpha = 5%，求 95% 分位点作为阈值 gamma
alpha = 0.05
p = 1 - alpha       # 0.95

gamma = chi2.ppf(p, df)
print("BDD threshold gamma:", gamma)

# 5. 基于阈值判断是否报警：J_i > gamma 则判为“有攻击/坏数据”
#    下面给出一个二元检测结果数组：1 表示检测为攻击，0 表示检测为正常
bdd_decision = (J_all > gamma).astype(int)  # (N,)

# bdd_decision[i] = 1 表示第 i 个样本被 BDD 判为“有问题”
print("Number of samples flagged as bad/attacked:", bdd_decision.sum())

# 5) 根据阈值判断是否报警：J_i > gamma -> 1 (alarm), else 0 (no alarm)
bdd_decision = (J_all > gamma).astype(int)  # (N,)

