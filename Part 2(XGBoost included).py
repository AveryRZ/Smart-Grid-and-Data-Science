def wls_state_estimation(z, H, W):
    """
    z: 测量向量 (34,)
    H: 测量矩阵 (34, 13)
    W: 权重矩阵 R^{-1} (34, 34)
    返回: x_hat (13,)
    """
    # 确保 z 是列向量形式 (34, 1)
    z = np.asarray(z).reshape(-1, 1)  # (34, 1)

    # 计算 (H^T W H)
    HTWH = H.T @ W @ H  # 13 x 13
    # 计算右端项 (H^T W z)
    HTWz = H.T @ W @ z  # 13 x 1

